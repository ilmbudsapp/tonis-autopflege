export function useSiteTypography() {
  const fontSans = '"Plus Jakarta Sans", system-ui, sans-serif';
  const fontDisplay = '"Syne", system-ui, sans-serif';
  const fontHeroHeadline = '"Eurostile Extd", system-ui, sans-serif';
  return { fontsReady: true, fontSans, fontDisplay, fontHeroHeadline };
}
