/**
 * Reads videos from public/VIDEO 1, deduplicates by SHA-256 of file bytes,
 * re-encodes to web-friendly MP4 (high quality CRF + slow preset, faststart),
 * writes posters as WebP, and generates src/generated/workVideos.ts.
 *
 * Usage: npm run videos:work
 */
import { execFileSync, spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ffmpeg from "ffmpeg-static";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const sourceDir = path.join(root, "public", "VIDEO 1");
const outDir = path.join(root, "public", "assets", "videos", "work");
const posterDir = path.join(outDir, "posters");
const generatedTs = path.join(root, "src", "generated", "workVideos.ts");
const heroPath = path.join(root, "public", "assets", "videos", "Tony Video Klip kompresovan.mp4");

const VIDEO_EXT = /\.(mp4|mov|webm|mkv|m4v)$/i;

/** Visok kvalitet: Lanczos skaliranje ako je širina > 1920; zarez u min() mora biti escapovan za ffmpeg. */
const SCALE_FILTER = "scale=min(1920\\,iw):-2:flags=lanczos";

function hasAudioTrack(filePath) {
  const r = spawnSync(ffmpeg, ["-hide_banner", "-i", filePath], { encoding: "utf8" });
  const err = `${r.stderr ?? ""}`;
  return /\bAudio:\s/.test(err);
}

async function walkVideos(dir) {
  const list = [];
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  for (const ent of entries) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      list.push(...(await walkVideos(full)));
    } else if (ent.isFile() && VIDEO_EXT.test(ent.name)) {
      list.push(full);
    }
  }
  return list;
}

async function sha256File(filePath) {
  const buf = await fs.readFile(filePath);
  return crypto.createHash("sha256").update(buf).digest("hex");
}

async function main() {
  await fs.mkdir(posterDir, { recursive: true });

  let heroHash = null;
  try {
    await fs.access(heroPath);
    heroHash = await sha256File(heroPath);
    console.log("Hero-Video Hash geladen (Duplikate dazu werden übersprungen).");
  } catch {
    /* kein Hero-File */
  }

  const allPaths = (await walkVideos(sourceDir)).sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }),
  );

  if (allPaths.length === 0) {
    console.warn("Keine Videos unter", sourceDir);
    await fs.writeFile(
      generatedTs,
      `/** Auto-generated — keine Quellvideos. Lege MP4/MOV in public/VIDEO 1/ und starte: npm run videos:work */\nexport const WORK_VIDEO_CLIPS = [] as const;\n`,
      "utf8",
    );
    return;
  }

  const seen = new Map();
  const uniquePaths = [];
  for (const p of allPaths) {
    const hash = await sha256File(p);
    if (heroHash && hash === heroHash) {
      console.warn("Überspringe (identisch mit Hero-Video):", path.relative(root, p));
      continue;
    }
    if (seen.has(hash)) {
      console.warn("Überspringe Duplikat (gleiche Bytes):", path.relative(root, p), "≡", path.relative(root, seen.get(hash)));
      continue;
    }
    seen.set(hash, p);
    uniquePaths.push(p);
  }

  console.log("Eindeutige Videos:", uniquePaths.length, "/", allPaths.length);

  const clips = [];
  let index = 0;
  for (const srcPath of uniquePaths) {
    index += 1;
    const clipName = `clip-${String(index).padStart(5, "0")}.mp4`;
    const posterName = `poster-${String(index).padStart(5, "0")}.webp`;
    const destPath = path.join(outDir, clipName);
    const posterPath = path.join(posterDir, posterName);

    const audio = hasAudioTrack(srcPath);
    const args = [
      "-y",
      "-i",
      srcPath,
      "-vf",
      SCALE_FILTER,
      "-c:v",
      "libx264",
      "-crf",
      "18",
      "-preset",
      "slow",
      "-pix_fmt",
      "yuv420p",
      "-movflags",
      "+faststart",
    ];
    if (audio) {
      args.push("-c:a", "aac", "-b:a", "192k", "-ar", "48000");
    } else {
      args.push("-an");
    }
    args.push(destPath);

    console.log("Encode", index, "/", uniquePaths.length, "→", clipName);
    execFileSync(ffmpeg, args, { stdio: "inherit" });

    const tmpPng = path.join(outDir, `_poster-${index}.png`);
    execFileSync(
      ffmpeg,
      ["-y", "-ss", "0.8", "-i", destPath, "-frames:v", "1", "-vf", SCALE_FILTER, "-update", "1", tmpPng],
      { stdio: "inherit" },
    );
    await sharp(tmpPng).webp({ quality: 90, effort: 5 }).toFile(posterPath);
    await fs.unlink(tmpPng).catch(() => {});

    clips.push({ file: clipName, poster: posterName });
    console.log("Poster", posterName);
  }

  const ts = `/** Auto-generated by scripts/build-work-videos-from-folder.mjs — do not edit by hand. */\nexport const WORK_VIDEO_CLIPS = [\n${clips.map((c) => `  { file: "${c.file}", poster: "${c.poster}" },`).join("\n")}\n] as const;\n`;
  await fs.writeFile(generatedTs, ts, "utf8");
  console.log("Wrote", generatedTs);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
