/**
 * Reads images from public/GALERIA, deduplicates by file content (SHA-256),
 * converts each unique image to high-quality WebP in public/assets/gallery-webp/,
 * and writes src/generated/galleryWebp.ts for the React gallery.
 *
 * Usage: npm run gallery:galeria
 */
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const sourceDir = path.join(root, "public", "GALERIA");
const outDir = path.join(root, "public", "assets", "gallery-webp");
const generatedTs = path.join(root, "src", "generated", "galleryWebp.ts");

const IMAGE_EXT = /\.(jpe?g|png|webp)$/i;

/** High visual fidelity: strong quality, effort; optional downscale only for very large raws. */
const WEBP_OPTIONS = {
  quality: 94,
  effort: 6,
  smartSubsample: false,
  alphaQuality: 100,
};

const MAX_LONG_EDGE = 5200;

async function walkFiles(dir) {
  const list = [];
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  for (const ent of entries) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      list.push(...(await walkFiles(full)));
    } else if (ent.isFile() && IMAGE_EXT.test(ent.name)) {
      list.push(full);
    }
  }
  return list;
}

async function sha256File(filePath) {
  const buf = await fs.readFile(filePath);
  return crypto.createHash("sha256").update(buf).digest("hex");
}

async function main() {
  await fs.mkdir(outDir, { recursive: true });
  await fs.mkdir(path.dirname(generatedTs), { recursive: true });

  const allPaths = (await walkFiles(sourceDir)).sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }),
  );

  if (allPaths.length === 0) {
    console.warn("No images found under", sourceDir);
    await fs.writeFile(
      generatedTs,
      `/** Auto-generated — no source images found. Run npm run gallery:galeria after adding files to public/GALERIA. */\nexport const GALLERY_WEBP_FILENAMES = [] as const;\n`,
      "utf8",
    );
    return;
  }

  const seen = new Map();
  const uniquePaths = [];
  for (const p of allPaths) {
    const hash = await sha256File(p);
    if (seen.has(hash)) {
      console.warn("Skip duplicate (same bytes):", path.relative(root, p), "≡", path.relative(root, seen.get(hash)));
      continue;
    }
    seen.set(hash, p);
    uniquePaths.push(p);
  }

  console.log("Unique images:", uniquePaths.length, "/", allPaths.length);

  let index = 0;
  const filenames = [];
  for (const srcPath of uniquePaths) {
    index += 1;
    const name = `gal-${String(index).padStart(5, "0")}.webp`;
    const destPath = path.join(outDir, name);

    let img = sharp(srcPath).rotate();
    const meta = await img.metadata();
    const w = meta.width ?? 0;
    const h = meta.height ?? 0;
    const longEdge = Math.max(w, h);
    if (longEdge > MAX_LONG_EDGE) {
      img = img.resize({
        width: MAX_LONG_EDGE,
        height: MAX_LONG_EDGE,
        fit: "inside",
        withoutEnlargement: true,
      });
    }

    await img.webp(WEBP_OPTIONS).toFile(destPath);
    filenames.push(name);
    console.log("Wrote", index, "/", uniquePaths.length, name, "←", path.basename(srcPath));
  }

  const ts = `/** Auto-generated by scripts/build-gallery-from-galeria.mjs — do not edit by hand. */\nexport const GALLERY_WEBP_FILENAMES = [\n${filenames.map((f) => `  "${f}",`).join("\n")}\n] as const;\n`;
  await fs.writeFile(generatedTs, ts, "utf8");
  console.log("Wrote", generatedTs);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
